class ReplyGenerator:
    def __init__(self) -> None:
        self.random = random.Random()

    def generate(self, context: dict) -> str:
        intent = context.get("intent", "normal")
        emotion = context.get("emotion", "nervous")

        if context.get("mode") == "autonomous" or intent == "quiet":
            return self._generate_autonomous(context)

        templates = INTENT_TEMPLATES.get(intent)
        if templates:
            return self.random.choice(templates)

        return self.random.choice(EMOTION_TEMPLATES.get(emotion, EMOTION_TEMPLATES["nervous"]))

    def _generate_autonomous(self, context: dict) -> str:
        drive_topic = context.get("drive_topic", "quiet")
        templates = AUTONOMOUS_TEMPLATES.get(drive_topic)
        if templates:
            return self.random.choice(templates)

        emotion = context.get("emotion", "lonely")
        return self.random.choice(EMOTION_TEMPLATES.get(emotion, EMOTION_TEMPLATES["lonely"]))
